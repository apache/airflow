"""Example Dag: a model drafts a release note, a person reviews it, and the loop repeats until they approve."""

from __future__ import annotations

# [START howto_loop_llm_review]
from airflow.providers.standard.operators.hitl import HITLOperator
from airflow.sdk import LoopDecision, Param, dag, task, task_group


@dag(tags=["example"])
def example_llm_review_loop():
    @task_group
    def draft_and_review():
        @task.llm(
            llm_conn_id="pydanticai_default",
            system_prompt="You write release notes for the users of a developer platform. Be plain and specific.",
        )
        def write(*, loop):
            prompt = (
                "Write a one-sentence release note for this change: webhook deliveries that fail with a 5xx "
                "response are now retried three times with exponential backoff instead of dropping the event."
            )
            if loop.index > 1:
                prompt += (
                    f"\nYour previous draft:\n{loop.previous['draft']}\n"
                    f"\nThe reviewer asked for these changes:\n{loop.previous['feedback']}\n"
                )
            return prompt

        draft = write()
        review = HITLOperator(
            task_id="review",
            subject="Review the release note",
            body="Please review the following, generated by the model:\n\n---\n\n{{ ti.xcom_pull(task_ids='draft_and_review.write') }}",
            options=["Approve", "Request changes"],
            params={"feedback": Param(None, type=["null", "string"], description="What should change?")},
        )
        draft >> review

        @task
        def decide(draft, response):
            return {
                "draft": draft,
                "approved": response["chosen_options"] == ["Approve"],
                "feedback": response["params_input"].get("feedback") or "",
            }

        decide(draft, review.output)

    def approved(*, loop):
        if loop.result["approved"]:
            return LoopDecision(stop=True, reason="approved")
        return LoopDecision(stop=False, reason=f"changes requested: {loop.result['feedback']}")

    reviewed = draft_and_review.loop(max_iterations=5, until=approved)

    @task
    def publish(rounds):
        print(f"Publishing after {len(rounds)} round(s): {rounds[-1]['draft']}")

    publish(reviewed["decide"].output)


example_llm_review_loop()
# [END howto_loop_llm_review]
