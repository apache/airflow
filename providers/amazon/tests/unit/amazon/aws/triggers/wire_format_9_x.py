"""
What amazon provider 9.x stores for a deferred task.

The triggerer rebuilds a trigger from the class path and kwargs that ``serialize()`` returned when the
task deferred, and the task then resumes in the method whose name was stored with it. A deferred task
can outlive a provider upgrade or rollback, so all of these are a wire format. ``test_wire_format.py``
checks that the current code still accepts everything listed here, which makes a failure there a
change to that format.

The entries are what 9.x releases wrote, so through 9.x they are only added:

- Add a trigger row for a new trigger, and another when a trigger starts serializing a new kwarg.
- Give every kwarg ``serialize()`` can write a value other than its default, so that a kwarg the
  trigger stops applying shows up as a changed value.
- Add a resume method when an operator starts deferring to another one, and keep the one it replaces:
  tasks deferred by an earlier release still resume there.

Before version 10.0.0 is released, the entries are regenerated from the last 9.x release, the one its
changelog names to upgrade from. Version 10.x keeps accepting all of them. Removing an entry fails
the tasks deferred before the upgrade, so it needs a major release and a changelog note that tells
users to let those tasks finish first.
"""

