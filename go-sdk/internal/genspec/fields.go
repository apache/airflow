// capitalizations are the --capitalization flags of the go-jsonschema step in
// airflow/spec.go, so that a field name here is the one go-jsonschema gives the
// struct field. TestCapitalizationsMatchTheGenerateDirective keeps the two lists equal.
var capitalizations = []string{"ID", "JSON", "FgColor", "MD", "UI", "XCom"}

// goFieldName returns the name go-jsonschema gives the struct field of a property. It
// splits the key at each character that is not a letter or a digit, and capitalizes each
// part, or writes the entry of capitalizations that the part equals ignoring case.
func goFieldName(key string) string {
	parts := strings.FieldsFunc(key, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	var name strings.Builder
	for _, part := range parts {
		name.WriteString(capitalize(part))
	}
	return name.String()
}

func capitalize(part string) string {
	for _, special := range capitalizations {
		if strings.EqualFold(special, part) {
			return special
		}
	}
	return strings.ToUpper(part[:1]) + part[1:]
}

// fieldEntry is one property of a spec definition, as the generated table holds it.
type fieldEntry struct {
	name, key string
	// schemaDefault is the Go literal of the default of the property, or empty when the
	// schema declares none.
	schemaDefault string
}

// emitFields returns the Go source of the tables of schema defaults, one for each
// definition of doc. doc is the schema that shapeForAuthoring and normalize wrote, so each
// definition has the title of its struct and holds the properties that become its fields.
// A table is keyed by the name of the struct field, as go-jsonschema writes it.
func emitFields(doc map[string]any) ([]byte, error) {
	definitions, ok := doc["definitions"].(map[string]any)
	if !ok {
		return nil, errNoDefinitions
	}
	var body bytes.Buffer
	for _, definition := range sortedKeys(definitions) {
		node, _ := definitions[definition].(map[string]any)
		title, _ := node["title"].(string)
		if title == "" {
			return nil, fmt.Errorf(
				"definitions/%s has no title to name its table after",
				definition,
			)
		}
		properties, _ := node["properties"].(map[string]any)
		fields, err := getFieldEntries(definition, properties)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(
			&body,
			"\n// %s holds the key and the schema default of each field of %s.\nvar %s = map[string]schemaField{\n",
			tableName(title),
			title,
			tableName(title),
		)
		for _, field := range fields {
			fmt.Fprintf(&body, "\t%q: {key: %q", field.name, field.key)
			if field.schemaDefault != "" {
				fmt.Fprintf(&body, ", schemaDefault: %s", field.schemaDefault)
			}
			body.WriteString("},\n")
		}
		body.WriteString("}\n")
	}
	source := "// Code generated by genspec, DO NOT EDIT.\n\npackage airflow\n" + body.String()
	return format.Source([]byte(source))
}

func tableName(title string) string {
	return strings.ToLower(title[:1]) + title[1:] + "Fields"
}

func getFieldEntries(definition string, properties map[string]any) ([]fieldEntry, error) {
	byName := make(map[string]string, len(properties))
	var fields []fieldEntry
	for _, key := range sortedKeys(properties) {
		name := goFieldName(key)
		if other, taken := byName[name]; taken {
			return nil, fmt.Errorf(
				"definitions/%s: the properties %q and %q both become the field %s",
				definition, other, key, name,
			)
		}
		byName[name] = key
		node, _ := properties[key].(map[string]any)
		literal, err := defaultLiteral(node["default"])
		if err != nil {
			return nil, fmt.Errorf("definitions/%s/properties/%s: %w", definition, key, err)
		}
		fields = append(fields, fieldEntry{name: name, key: key, schemaDefault: literal})
	}
	slices.SortFunc(fields, func(a, b fieldEntry) int { return cmp.Compare(a.name, b.name) })
	return fields, nil
}

// defaultLiteral returns the Go literal of a schema default. A number that the schema
// writes with a fraction or an exponent stays a float64, such as retry_delay's 300.0, and
// any other number is an int, because readSchema decodes a number as a json.Number. A null
// default says the property has none, as an absent one does.
func defaultLiteral(value any) (string, error) {
	switch value := value.(type) {
	case nil:
		return "", nil
	case bool:
		return strconv.FormatBool(value), nil
	case string:
		return strconv.Quote(value), nil
	case json.Number:
		if strings.ContainsAny(value.String(), ".eE") {
			number, err := value.Float64()
			if err != nil {
				return "", err
			}
			literal := strconv.FormatFloat(number, 'f', -1, 64)
			if !strings.Contains(literal, ".") {
				literal += ".0"
			}
			return literal, nil
		}
		if _, err := value.Int64(); err != nil {
			return "", err
		}
		return value.String(), nil
	}
	return "", fmt.Errorf("the default %v is a %T, which the table cannot hold", value, value)
}
