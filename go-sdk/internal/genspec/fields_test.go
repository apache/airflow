func TestGoFieldNameMatchesGoJSONSchema(t *testing.T) {
	for key, want := range map[string]string{
		"fail_fast":          "FailFast",
		"_task_display_name": "TaskDisplayName",
		"doc_md":             "DocMD",
		"do_xcom_push":       "DoXComPush",
		"prefix_group_id":    "PrefixGroupID",
		"ui_fgcolor":         "UIFgColor",
		"task_id":            "TaskID",
		"dagrun_timeout":     "DagrunTimeout",
	} {
		assert.Equal(t, want, goFieldName(key), key)
	}
}

func TestCapitalizationsMatchTheGenerateDirective(t *testing.T) {
	raw, err := os.ReadFile("../../airflow/spec.go")
	require.NoError(t, err)
	var flags []string
	for _, match := range regexp.MustCompile(`--capitalization (\S+)`).FindAllStringSubmatch(string(raw), -1) {
		flags = append(flags, match[1])
	}
	assert.Equal(t, capitalizations, flags)
}

func TestEmitFieldsWritesTheKeyAndDefaultOfEachField(t *testing.T) {
	// readSchema decodes a number as a json.Number, which a plain Unmarshal does not.
	raw := `{"definitions": {"operator": {"title": "TaskSpec", "properties": {
		"retry_delay": {"default": 300.0},
		"retries": {"default": 0},
		"do_xcom_push": {"default": true},
		"owner": {"default": "airflow"},
		"queue": {"default": null},
		"doc_md": {}
	}}}}`
	path := t.TempDir() + "/schema.json"
	require.NoError(t, os.WriteFile(path, []byte(raw), 0o644))
	doc, err := readSchema(path)
	require.NoError(t, err)

	source, err := emitFields(doc)

	require.NoError(t, err)
	got := string(source)
	assert.Contains(t, got, "var taskSpecFields = map[string]schemaField{")
	for _, entry := range []string{
		`"DocMD":`, `{key: "doc_md"}`,
		`{key: "retry_delay", schemaDefault: 300.0}`,
		`{key: "retries", schemaDefault: 0}`,
		`{key: "do_xcom_push", schemaDefault: true}`,
		`{key: "owner", schemaDefault: "airflow"}`,
		`{key: "queue"}`,
	} {
		assert.Contains(t, got, entry)
	}
	assert.True(t, strings.HasPrefix(got, "// Code generated by genspec, DO NOT EDIT."))
}

func TestEmitFieldsRejects(t *testing.T) {
	for name, tt := range map[string]struct{ schema, want string }{
		"a definition without a title": {
			`{"definitions": {"dag": {"properties": {}}}}`,
			"definitions/dag has no title",
		},
		"two properties with one field name": {
			`{"definitions": {"dag": {"title": "DagSpec", "properties": {"doc_md": {}, "doc-md": {}}}}}`,
			"both become the field DocMD",
		},
		"a default that is not a scalar": {
			`{"definitions": {"dag": {"title": "DagSpec", "properties": {"tags": {"default": []}}}}}`,
			"the table cannot hold",
		},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := emitFields(schemaFrom(t, tt.schema))

			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.want)
		})
	}
}

func TestEmitFieldsReadsTheShapedCoreSchema(t *testing.T) {
	doc := readCoreSchema(t)
	require.NoError(t, shapeForAuthoring(doc, authoringShapes))
	require.NoError(t, normalize(doc, specTitles))

	source, err := emitFields(doc)

	require.NoError(t, err)
	got := string(source)
	for _, table := range []string{"dagSpecFields", "taskSpecFields", "taskGroupSpecFields"} {
		assert.Contains(t, got, "var "+table+" = ")
	}
	assert.Contains(t, got, `"RetryDelay"`)
	assert.Contains(t, got, "schemaDefault: 300.0")
}
