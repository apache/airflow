ADVISORY = """
The trust list changed. Entries that disappeared are checksums nothing resolves
any more - usually versions superseded by a dependency bump. They stayed
trusted, so a future direct or transitive dependency could have pulled that
exact version back in with nobody reviewing its checksum.

Review every entry in the diff before staging it: generating the file records
what the repositories served, it does not make those bytes trustworthy.
"""


class RegenerationFailedError(RuntimeError):
    """Gradle could not regenerate the metadata within the attempt budget."""


class UnsafeMetadataError(ValueError):
    """The regenerated metadata is not a plain list of generated checksums."""


def build_empty_metadata(committed: str) -> str:
    """Return the committed metadata with its component list emptied."""
    kept: list[str] = []
    for line in committed.splitlines():
        if "<components>" in line:
            kept += ["   <components/>", "</verification-metadata>"]
            break
        kept.append(line)
    return "\n".join(kept) + "\n"


def insert_license_header(metadata: str) -> str:
    """Put the ASF header back after the XML declaration, unless Gradle kept one."""
    if "Licensed to the Apache Software Foundation" in metadata:
        return metadata
    declaration, *rest = metadata.splitlines()
    return "\n".join([declaration, LICENSE_HEADER, *rest]) + "\n"


def run_gradle() -> bool:
    """Both properties are needed for the run to reach the end: signing has no key
    here, and sourceTarball has no default ref."""
    result = subprocess.run(
        [
            "./gradlew",
            "--no-daemon",
            "--write-verification-metadata",
            "sha256",
            "--refresh-dependencies",
            *GRADLE_TASKS,
            "-PskipSigning=true",
            "-PgitRef=HEAD",
        ],
        cwd=JAVA_SDK,
        check=False,
    )
    return result.returncode == 0


def regenerate(
    metadata: pathlib.Path,
    gradle: Callable[[], bool],
    sleep: Callable[[float], None] = time.sleep,
) -> None:
    """Rewrite the metadata in place, putting the committed file back if the run never succeeds."""
    committed = metadata.read_text()
    restore = True
    try:
        for attempt in range(1, MAX_ATTEMPTS + 1):
            print(f"==> Regenerating verification metadata (attempt {attempt}/{MAX_ATTEMPTS})", flush=True)
            metadata.write_text(build_empty_metadata(committed))
            if gradle():
                metadata.write_text(insert_license_header(metadata.read_text()))
                restore = False
                return
            if attempt < MAX_ATTEMPTS:
                print(f"Regeneration failed, retrying in {RETRY_DELAY_SECONDS}s", file=sys.stderr, flush=True)
                sleep(RETRY_DELAY_SECONDS)
        raise RegenerationFailedError(f"Regeneration failed after {MAX_ATTEMPTS} attempts")
    finally:
        if restore:
            metadata.write_text(committed)


def metadata_changed(metadata: pathlib.Path) -> bool:
    result = subprocess.run(["git", "diff", "--quiet", "--", str(metadata)], cwd=REPO_ROOT, check=False)
    return result.returncode != 0


def get_checksum_map(regenerated: str) -> dict[tuple[str, str, str, str], frozenset[str]]:
    """Parse the metadata, requiring the exact shape Gradle writes, and map artifacts to their hashes."""
    if "<!DOCTYPE" in regenerated:
        raise UnsafeMetadataError("DOCTYPE declarations are not allowed")
    try:
        root = ET.fromstring(regenerated)
    except ET.ParseError as error:
        raise UnsafeMetadataError(f"malformed XML: {error}") from error
    if [child.tag for child in root] != [f"{XML_NAMESPACE}configuration", f"{XML_NAMESPACE}components"]:
        raise UnsafeMetadataError("root must contain exactly <configuration> then <components>")
    checksums: dict[tuple[str, str, str, str], frozenset[str]] = {}
    for component in root[1]:
        if component.tag != f"{XML_NAMESPACE}component" or set(component.attrib) != {
            "group",
            "name",
            "version",
        }:
            raise UnsafeMetadataError(f"unexpected element under <components>: {component.tag}")
        coordinate = (component.attrib["group"], component.attrib["name"], component.attrib["version"])
        for artifact in component:
            if artifact.tag != f"{XML_NAMESPACE}artifact" or set(artifact.attrib) != {"name"}:
                raise UnsafeMetadataError(f"unexpected element under <component>: {artifact.tag}")
            values: set[str] = set()
            for sha256 in artifact:
                if (
                    sha256.tag != f"{XML_NAMESPACE}sha256"
                    or set(sha256.attrib) != {"value", "origin"}
                    or not SHA256_PATTERN.fullmatch(sha256.attrib["value"])
                    or sha256.attrib["origin"] != GENERATED_ORIGIN
                    or len(sha256)
                ):
                    raise UnsafeMetadataError(f"unexpected element under <artifact>: {sha256.tag}")
                values.add(sha256.attrib["value"])
            key = (*coordinate, artifact.attrib["name"])
            if not values:
                raise UnsafeMetadataError(f"entry without a checksum: {'/'.join(key)}")
            # Gradle merges duplicates, so a second entry could add a hash to a retained artifact.
            if key in checksums:
                raise UnsafeMetadataError(f"duplicate entry: {'/'.join(key)}")
            checksums[key] = frozenset(values)
    return checksums


def validate_regenerated(committed: str, regenerated: str) -> None:
    """Raise UnsafeMetadataError unless `regenerated` only adds or removes generated checksum entries."""
    checksums = get_checksum_map(regenerated)
    marker = "<components>"
    if marker not in regenerated or regenerated.split(marker, 1)[0] != committed.split(marker, 1)[0]:
        raise UnsafeMetadataError("text before <components> differs from the committed file")
    committed_checksums = get_checksum_map(committed)
    for key, values in checksums.items():
        if key in committed_checksums and committed_checksums[key] != values:
            raise UnsafeMetadataError(f"checksum changed for a retained artifact: {'/'.join(key)}")


def main(argv: Sequence[str] = ()) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validate", type=pathlib.Path, metavar="FILE")
    args = parser.parse_args(argv)
    if args.validate:
        try:
            validate_regenerated(METADATA.read_text(), args.validate.read_text())
        except UnsafeMetadataError as error:
            print(f"ERROR: {error}", file=sys.stderr)
            return 1
        return 0
    try:
        regenerate(METADATA, run_gradle)
    except RegenerationFailedError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    if metadata_changed(METADATA):
        print(ADVISORY, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
