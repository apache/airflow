"""Verify the skill-eval ran against the current guidance files.

``dev/skill-evals/eval.py`` records a hash of its inputs in
``dev/skill-evals/last-eval-hash.txt`` after every completed run. This hook
recomputes the hash from the current file contents and fails when AGENTS.md
or the eval cases changed without a re-run. A skill with its own suite under
``dev/skill-evals/skills/<name>/`` is checked the same way against the hash in
that suite, recorded by a ``SKILL_NAME=<name>`` run. The hash proves the eval
*ran* on this exact content — not that all cases passed.

The comparison is pure file content — no git state — so the hook behaves
identically at commit time, at push time, and in CI (``prek --all-files``).
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
AGENTS_FILE = REPO_ROOT / "AGENTS.md"
CASES_DIR = REPO_ROOT / "dev" / "skill-evals" / "cases"
HASH_FILE = REPO_ROOT / "dev" / "skill-evals" / "last-eval-hash.txt"
SKILLS_DIR = REPO_ROOT / ".agents" / "skills"
SKILL_EVALS_DIR = REPO_ROOT / "dev" / "skill-evals" / "skills"

HASH_FILE_HEADER = """\
# Generated by dev/skill-evals/eval.py — do not edit or resolve conflicts by hand.
# Run `{command}` to regenerate.
"""


def eval_command(skill_name: str | None = None) -> str:
    """Return the command that runs the eval for AGENTS.md, or for one skill's suite."""
    command = "prek run run-skill-eval --hook-stage manual --all-files"
    return f"SKILL_NAME={skill_name} {command}" if skill_name else command


def _hash_entries(entries: list[tuple[str, Path]]) -> str:
    # Labels are hashed alongside contents so renaming an input changes the hash.
    digest = hashlib.sha256()
    for label, path in entries:
        digest.update(label.encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def compute_guidance_hash(agents_file: Path, cases_dir: Path) -> str:
    """Hash the skill-eval inputs: AGENTS.md plus every case file.

    Skills are hashed separately, per suite, by :func:`compute_skill_hash`: an eval
    run tests one skill at a time, so one hash over all of them could never be
    recorded by a single run.
    """
    entries = [("AGENTS.md", agents_file)]
    entries += [(f"cases/{path.name}", path) for path in sorted(cases_dir.glob("*.yaml"))]
    return _hash_entries(entries)


def compute_skill_hash(skill_file: Path, suite_dir: Path) -> str:
    """Hash one skill's eval inputs: its SKILL.md, the suite's output schema and every case file.

    AGENTS.md is left out: it is gated by :func:`compute_guidance_hash`, and including
    it here would make every AGENTS.md edit re-run every skill suite.
    """
    entries = [("SKILL.md", skill_file), ("output-schema.json", suite_dir / "output-schema.json")]
    entries += [(f"cases/{path.name}", path) for path in sorted((suite_dir / "cases").glob("*.yaml"))]
    return _hash_entries(entries)


def skill_suites(skill_evals_dir: Path) -> list[Path]:
    """Return the skill suite directories, the ones that hold cases."""
    if not skill_evals_dir.is_dir():
        return []
    return sorted(path for path in skill_evals_dir.iterdir() if (path / "cases").is_dir())


def read_recorded_hash(hash_file: Path) -> str | None:
    """Return the hash recorded in ``hash_file``, or None if absent."""
    if not hash_file.is_file():
        return None
    for line in hash_file.read_text().splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            return stripped
    return None


def write_recorded_hash(value: str, hash_file: Path, skill_name: str | None = None) -> None:
    """Record ``value`` with a regeneration note, like breeze's output-commands-hash.txt."""
    hash_file.write_text(f"{HASH_FILE_HEADER.format(command=eval_command(skill_name))}{value}\n")


def main() -> int:
    stale: list[str] = []
    if compute_guidance_hash(AGENTS_FILE, CASES_DIR) != read_recorded_hash(HASH_FILE):
        stale.append(
            "AGENTS.md or dev/skill-evals/cases/ changed without re-running the"
            " skill-eval\n(dev/skill-evals/last-eval-hash.txt does not match).\n"
            "\n"
            f"  Run:  {eval_command()}\n"
            "        then commit the updated dev/skill-evals/last-eval-hash.txt"
        )
    for suite_dir in skill_suites(SKILL_EVALS_DIR):
        name = suite_dir.name
        skill_file = SKILLS_DIR / name / "SKILL.md"
        if not skill_file.is_file():
            stale.append(
                f"dev/skill-evals/skills/{name}/ has cases, but .agents/skills/{name}/SKILL.md"
                " does not exist.\n  Rename or remove the suite along with the skill."
            )
            continue
        hash_file = suite_dir / "last-eval-hash.txt"
        if compute_skill_hash(skill_file, suite_dir) != read_recorded_hash(hash_file):
            stale.append(
                f"The {name} skill or its cases changed without re-running its skill-eval\n"
                f"(dev/skill-evals/skills/{name}/last-eval-hash.txt does not match).\n"
                "\n"
                f"  Run:  {eval_command(name)}\n"
                f"        then commit the updated dev/skill-evals/skills/{name}/last-eval-hash.txt"
            )
    if not stale:
        return 0
    print(
        "\n\n".join(stale) + "\n"
        "\n"
        "  WIP commit: SKIP=check-eval-hash git commit ...\n"
        "  Can't run the eval? Ask a maintainer to run it and push the updated\n"
        "  hash file to your PR branch (see dev/skill-evals/README.md).",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
