"""TaskInstanceLaunch model for durable executor launch records."""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import TYPE_CHECKING, cast

from sqlalchemy import (
    CheckConstraint,
    Index,
    String,
    and_,
    func,
    select,
    update,
)
from sqlalchemy.orm import Mapped, mapped_column

from airflow._shared.timezones import timezone
from airflow.models.base import Base
from airflow.utils.sqlalchemy import UtcDateTime

if TYPE_CHECKING:
    from sqlalchemy.engine import CursorResult
    from sqlalchemy.orm import Session


class TaskInstanceLaunchState(str, Enum):
    """All possible states of a task instance launch record."""

    ACTIVE = "active"
    CONSUMED = "consumed"
    SUPERSEDED = "superseded"

    def __str__(self) -> str:
        return self.value


TERMINAL_STATES = frozenset((TaskInstanceLaunchState.CONSUMED, TaskInstanceLaunchState.SUPERSEDED))


class TaskInstanceLaunch(Base):
    """
    Durable launch record for executor workload execution.

    Tracks executor tokens for task instance launches across scheduler failover/adoption.
    Enables validation that reported executor IDs match the executor that was originally
    assigned, preventing stale or spoofed executor responses.
    """

    __tablename__ = "task_instance_launch"

    # Bounded launch token, generated by the scheduler and propagated unchanged to the worker.
    token: Mapped[str] = mapped_column(String(256), primary_key=True, nullable=False)

    # Task instance reference (no FK - already deleted TIs must allow lookup)
    task_instance_id: Mapped[str] = mapped_column(String(250), nullable=False)

    # Context for reconstruction/audit
    dag_id: Mapped[str] = mapped_column(String(250), nullable=False)
    task_id: Mapped[str] = mapped_column(String(250), nullable=False)
    run_id: Mapped[str] = mapped_column(String(250), nullable=False)
    map_index: Mapped[int] = mapped_column(default=-1, nullable=False)
    try_number: Mapped[int] = mapped_column(nullable=False)

    # Executor identification
    executor: Mapped[str] = mapped_column(String(256), nullable=False)

    # Launch state machine: active -> consumed | superseded
    state: Mapped[str] = mapped_column(String(20), nullable=False, default=TaskInstanceLaunchState.ACTIVE)

    # Lifecycle timestamps
    created_at: Mapped[datetime] = mapped_column(
        UtcDateTime, default=timezone.utcnow, server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        UtcDateTime,
        default=timezone.utcnow,
        server_default=func.now(),
        onupdate=timezone.utcnow,
        nullable=False,
    )
    consumed_at: Mapped[datetime | None] = mapped_column(UtcDateTime, nullable=True)
    superseded_at: Mapped[datetime | None] = mapped_column(UtcDateTime, nullable=True)

    # Indexes for common queries
    __table_args__ = (
        Index("idx_task_instance_launch_state_updated", "state", "updated_at"),
        Index("idx_task_instance_launch_task_instance_id", "task_instance_id"),
        Index("idx_task_instance_launch_created_at", "created_at"),
        CheckConstraint(
            "state IN ('active', 'consumed', 'superseded')",
            name="state_enum",
        ),
    )

    @classmethod
    def mark_consumed(
        cls,
        token: str,
        session: Session,
    ) -> bool:
        """
        Mark a launch record as consumed (token was accepted by executor).

        Uses guarded UPDATE to prevent race conditions.

        :param token: The token to mark consumed
        :param session: SQLAlchemy session
        :return: True if record was updated, False if not found or not in ACTIVE state
        """
        result = session.execute(
            update(cls)
            .where(and_(cls.token == token, cls.state == TaskInstanceLaunchState.ACTIVE))
            .values(
                state=TaskInstanceLaunchState.CONSUMED,
                consumed_at=timezone.utcnow(),
                updated_at=timezone.utcnow(),
            )
        )
        return cast("CursorResult", result).rowcount > 0

    @classmethod
    def mark_superseded(
        cls,
        token: str,
        session: Session,
    ) -> bool:
        """
        Mark a launch record as superseded (replaced by a newer launch).

        Uses guarded UPDATE to prevent race conditions.

        :param token: The token to mark superseded
        :param session: SQLAlchemy session
        :return: True if record was updated, False if not found or not in ACTIVE state
        """
        result = session.execute(
            update(cls)
            .where(and_(cls.token == token, cls.state == TaskInstanceLaunchState.ACTIVE))
            .values(
                state=TaskInstanceLaunchState.SUPERSEDED,
                superseded_at=timezone.utcnow(),
                updated_at=timezone.utcnow(),
            )
        )
        return cast("CursorResult", result).rowcount > 0

    @classmethod
    def get_active_by_token(
        cls,
        token: str,
        session: Session,
    ) -> TaskInstanceLaunch | None:
        """
        Retrieve an active launch record by token.

        :param token: The token to lookup
        :param session: SQLAlchemy session
        :return: The TaskInstanceLaunch record if found and active, else None
        """
        return session.scalar(
            select(cls).where(
                and_(
                    cls.token == token,
                    cls.state == TaskInstanceLaunchState.ACTIVE,
                )
            )
        )

    @classmethod
    def get_by_token(
        cls,
        token: str,
        session: Session,
    ) -> TaskInstanceLaunch | None:
        """
        Retrieve a launch record by token (any state).

        :param token: The token to lookup
        :param session: SQLAlchemy session
        :return: The TaskInstanceLaunch record if found, else None
        """
        return session.get(cls, token)

    @classmethod
    def get_task_instance_active_launches(
        cls,
        task_instance_id: str,
        session: Session,
    ) -> list[TaskInstanceLaunch]:
        """
        Get all active launch records for a task instance.

        :param task_instance_id: The task instance ID to query
        :param session: SQLAlchemy session
        :return: List of active launch records
        """
        return list(
            session.scalars(
                select(cls).where(
                    and_(
                        cls.task_instance_id == task_instance_id,
                        cls.state == TaskInstanceLaunchState.ACTIVE,
                    )
                )
            ).all()
        )
